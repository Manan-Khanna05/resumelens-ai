import { useState } from "react";
import type { AnalysisResult } from "./types";
import { SAMPLES } from "./samples";

function scoreColour(score: number): string {
  if (score >= 80) return "#0071e3";
  if (score >= 65) return "#0066cc";
  if (score >= 50) return "#1d1d1f";
  return "#d92d20";
}

export default function App() {
  const [resume, setResume] = useState("");
  const [jobDescription, setJobDescription] = useState("");
  const [result, setResult] = useState<AnalysisResult | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [activeSample, setActiveSample] = useState("");

  function loadSample(id: string) {
    const sample = SAMPLES.find((s) => s.id === id);
    if (!sample) return;
    setResume(sample.resume);
    setJobDescription(sample.jobDescription);
    setActiveSample(id);
    setResult(null);
    setError("");
  }

  async function analyse() {
    setLoading(true);
    setError("");
    setResult(null);
    try {
      const res = await fetch("/api/analyze", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ resume, jobDescription }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || "Analysis failed.");
      setResult(data as AnalysisResult);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Analysis failed. Is the server running?");
    } finally {
      setLoading(false);
    }
  }

  function downloadChecklist() {
    if (!result) return;
    const lines = [
      "# ResumeLens AI — Improved-skills checklist",
      "",
      `Score: ${result.score}/100 — ${result.verdict}`,
      "",
      "## Do this next",
      ...result.checklist.map((c) => `- [ ] ${c}`),
      "",
      "## Missing skills",
      ...result.missing.map((m) => `- ${m}`),
      "",
      "## Matched skills",
      ...result.matched.map((m) => `- ${m}`),
      "",
      "Generated by ResumeLens AI (on-device, rule-based analysis).",
    ].join("\n");
    const blob = new Blob([lines], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "resumelens-checklist.md";
    a.click();
    URL.revokeObjectURL(url);
  }

  const radius = 62;
  const circumference = 2 * Math.PI * radius;

  return (
    <div className="page">
      <header className="nav">
        <div className="nav-inner">
          <span className="logo">ResumeLens AI</span>
          <span className="nav-note">On-device analysis · No API key</span>
        </div>
      </header>

      <main>
        <section className="hero">
          <h1>Your resume, seen<br />through a recruiter&rsquo;s lens.</h1>
          <p className="hero-sub">
            Paste your resume and a job description. Get an ATS-style match
            score, matched and missing skills, and concrete fixes — in seconds.
          </p>
          <p className="hero-note">
            On-device, rule-based AI. No external API, no key needed, and your
            text is not sent to any AI vendor.
          </p>
        </section>

        <section className="samples">
          <p className="section-label">Try it instantly — load a sample pair</p>
          <div className="sample-row">
            {SAMPLES.map((s) => (
              <button
                key={s.id}
                type="button"
                className={`btn btn-secondary sample-btn${activeSample === s.id ? " active" : ""}`}
                onClick={() => loadSample(s.id)}
              >
                {s.title}
              </button>
            ))}
            <button
              type="button"
              className="btn btn-tertiary"
              onClick={() => {
                setResume("");
                setJobDescription("");
                setResult(null);
                setError("");
                setActiveSample("");
              }}
            >
              Clear
            </button>
          </div>
          {activeSample && (
            <p className="sample-caption">
              {SAMPLES.find((s) => s.id === activeSample)?.subtitle}
            </p>
          )}
        </section>

        <section className="inputs">
          <div className="input-card">
            <label htmlFor="resume">Your resume</label>
            <textarea
              id="resume"
              value={resume}
              onChange={(e) => setResume(e.target.value)}
              placeholder="Paste your full resume text here…"
              rows={14}
            />
            <p className="count">{resume.trim() ? `${resume.trim().split(/\s+/).length} words` : "0 words"}</p>
          </div>
          <div className="input-card">
            <label htmlFor="jd">Job description</label>
            <textarea
              id="jd"
              value={jobDescription}
              onChange={(e) => setJobDescription(e.target.value)}
              placeholder="Paste the job description here…"
              rows={14}
            />
            <p className="count">{jobDescription.trim() ? `${jobDescription.trim().split(/\s+/).length} words` : "0 words"}</p>
          </div>
        </section>

        <div className="actions">
          <button
            type="button"
            className="btn btn-primary"
            onClick={analyse}
            disabled={loading || resume.trim().length < 50 || jobDescription.trim().length < 50}
          >
            {loading ? "Analysing…" : "Analyse my resume"}
          </button>
          <p className="hint">Needs at least 50 characters in each box.</p>
        </div>

        {error && <p className="error" role="alert">{error}</p>}

        {result && (
          <section className="results">
            <div className="score-card card">
              <div className="gauge">
                <svg width="160" height="160" viewBox="0 0 160 160" aria-label={`Score ${result.score} out of 100`}>
                  <circle cx="80" cy="80" r={radius} fill="none" stroke="#e5e7eb" strokeWidth="10" />
                  <circle
                    cx="80"
                    cy="80"
                    r={radius}
                    fill="none"
                    stroke={scoreColour(result.score)}
                    strokeWidth="10"
                    strokeLinecap="round"
                    strokeDasharray={circumference}
                    strokeDashoffset={circumference * (1 - result.score / 100)}
                    transform="rotate(-90 80 80)"
                  />
                </svg>
                <div className="gauge-text">
                  <span className="gauge-number">{result.score}</span>
                  <span className="gauge-outof">/ 100</span>
                </div>
              </div>
              <div>
                <h2>ATS match score</h2>
                <p>{result.verdict}</p>
                <p className="muted">
                  {result.counts.matchedSkills} of {result.counts.requiredSkills} required
                  skills found · {result.counts.resumeWords} words ·{" "}
                  {result.counts.actionVerbs} action verbs ·{" "}
                  {result.counts.quantifiedResults} quantified results
                </p>
                <button type="button" className="btn btn-primary" onClick={downloadChecklist}>
                  Download checklist
                </button>
              </div>
            </div>

            <h2 className="section-title">Score breakdown</h2>
            <div className="grid">
              {result.breakdown.map((b) => (
                <div className="card" key={b.label}>
                  <div className="breakdown-head">
                    <strong>{b.label}</strong>
                    <span>{b.value} / 100</span>
                  </div>
                  <div className="bar">
                    <div className="bar-fill" style={{ width: `${b.value}%` }} />
                  </div>
                  <p className="muted">Weight {b.weight} · {b.detail}</p>
                </div>
              ))}
            </div>

            <div className="grid two">
              <div className="card">
                <h3>Matched skills ({result.matched.length})</h3>
                {result.matched.length === 0 ? (
                  <p className="muted">None of the job&rsquo;s required skills were found.</p>
                ) : (
                  <div className="chips">
                    {result.matched.map((s) => (
                      <span className="chip chip-good" key={s}>{s}</span>
                    ))}
                  </div>
                )}
              </div>
              <div className="card">
                <h3>Missing skills ({result.missing.length})</h3>
                {result.missing.length === 0 ? (
                  <p className="muted">Every required skill in the job description is present.</p>
                ) : (
                  <div className="chips">
                    {result.missing.map((s) => (
                      <span className="chip chip-missing" key={s}>{s}</span>
                    ))}
                  </div>
                )}
              </div>
            </div>

            <h2 className="section-title">Section-by-section feedback</h2>
            <div className="card">
              {result.sections.map((s) => (
                <div className="section-row" key={s.key}>
                  <span className={s.present ? "dot dot-yes" : "dot dot-no"}>{s.present ? "✓" : "—"}</span>
                  <span>{s.label}</span>
                  <span className="muted">{s.present ? "Found" : "Missing — add this section"}</span>
                </div>
              ))}
            </div>

            <h2 className="section-title">Rewrite suggestions</h2>
            <div className="suggestions">
              {result.suggestions.map((s, i) => (
                <div className="card suggestion" key={i}>
                  <span className="chip">{s.category} · {s.priority}</span>
                  <p>{s.text}</p>
                </div>
              ))}
            </div>

            <p className="method">{result.method}</p>
          </section>
        )}

        <section className="how">
          <h2 className="section-title">How it works</h2>
          <div className="grid three">
            <div className="card">
              <h3>1. Paste</h3>
              <p>Your resume and the job description. Nothing is uploaded to an AI vendor.</p>
            </div>
            <div className="card">
              <h3>2. Analyse</h3>
              <p>The server tokenises both texts, extracts skills from a curated list, and compares wording with cosine similarity.</p>
            </div>
            <div className="card">
              <h3>3. Fix</h3>
              <p>Follow the checklist, add the missing skills with real examples, and re-run the analysis.</p>
            </div>
          </div>
          <p className="muted">
            Honest note: this is a rule-based heuristic, not a real ATS and not
            GPT/OpenAI. Scores are a guide for tailoring your resume, not a
            guarantee of shortlisting.
          </p>
        </section>
      </main>

      <footer>
        <p>ResumeLens AI — built by Manan Khanna · MIT License · On-device, rule-based analysis</p>
      </footer>
    </div>
  );
}
